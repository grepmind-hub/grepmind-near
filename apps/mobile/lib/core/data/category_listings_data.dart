  /// Returns listings for a given category slug. If slug is null or 'all', returns all listings.
  /// Can be optionally filtered by search query, locality, or maximum distance in meters.
  static List<Business> getListingsForCategory(
    String? categorySlug, {
    String? query,
    String? locality,
    String? pincode,
    int? maxRadiusM,
    String? sortBy, // 'distance', 'rating', 'relevance'
  }) {
    var items = allListings;

    if (categorySlug != null &&
        categorySlug.isNotEmpty &&
        categorySlug != 'all') {
      items = items.where((b) => b.categorySlug == categorySlug).toList();
    }

    if (query != null && query.trim().isNotEmpty) {
      final q = query.trim().toLowerCase();
      items = items.where((b) {
        return b.name.toLowerCase().contains(q) ||
            (b.description?.toLowerCase().contains(q) ?? false) ||
            (b.locality?.toLowerCase().contains(q) ?? false) ||
            (b.postalCode?.contains(q) ?? false);
      }).toList();
    }

    if (locality != null && locality.trim().isNotEmpty && locality != 'All') {
      items = items.where((b) => b.locality == locality).toList();
    }

    if (pincode != null && pincode.trim().isNotEmpty && pincode != 'All') {
      items = items.where((b) => b.postalCode == pincode).toList();
    }

    if (maxRadiusM != null && maxRadiusM > 0) {
      items = items.where((b) => (b.distanceM ?? 0) <= maxRadiusM).toList();
    }

    final sorted = List<Business>.from(items);
    if (sortBy == 'distance') {
      sorted.sort((a, b) => (a.distanceM ?? 0).compareTo(b.distanceM ?? 0));
    } else if (sortBy == 'rating') {
      sorted.sort((a, b) => (b.rating ?? 0).compareTo(a.rating ?? 0));
    }

    return sorted;
  }

  /// Returns unique available pincodes across all listings.
  static List<String> getAvailablePincodes([String? categorySlug]) {
    final listings = categorySlug != null && categorySlug != 'all'
        ? allListings.where((b) => b.categorySlug == categorySlug)
        : allListings;
    final Set<String> codes = {};
    for (final b in listings) {
      if (b.postalCode != null && b.postalCode!.isNotEmpty) {
        codes.add(b.postalCode!);
      }
    }
    final list = codes.toList()..sort();
    return list;
  }

  /// Returns unique localities across all listings.
  static List<String> getAvailableLocalities([String? categorySlug]) {
    final listings = categorySlug != null && categorySlug != 'all'
        ? allListings.where((b) => b.categorySlug == categorySlug)
        : allListings;
    final Set<String> locs = {};
    for (final b in listings) {
      if (b.locality != null && b.locality!.isNotEmpty) {
        locs.add(b.locality!);
      }
    }
    final list = locs.toList()..sort();
    return list;
  }
